#!/usr/bin/env bun
/**
 * Builds the installable release archive (dev tooling only):
 *
 *   bun scripts/release.ts [--out <dir>] [--skip-data-check] [--download-url <url>]
 *
 * => dist/file-icons-<version>.zip with a single top-level `file-icons/` folder containing
 *    plugin.json (without `meta`), README.md, LICENSE, THIRD_PARTY_NOTICES.md, CHANGELOG.md,
 *    config/, database/ (migrations), lang/, resources/{data,icons,views}/ and src/. Everything
 *    else (scripts incl. scripts/.cache, tests, node_modules, package.json, bun.lock, .github, dist,
 *    dotfiles) is left out.
 *
 * The archive is reproducible: entries are sorted, timestamps are fixed (SOURCE_DATE_EPOCH if
 * set, else 1980-02-01 00:00), permissions are normalised (0644 files / 0755 directories).
 * Before writing it, the generated data is checked with `scripts/build-data.ts --check`.
 *
 * With --download-url, it also writes <out>/update.json for Pelican's plugin updater
 * ({"*": {version, download_url, sha256}}). `{version}` in the URL is replaced with the version.
 */
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, lstatSync, mkdirSync, readdirSync, readFileSync, renameSync, writeFileSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';
import { parseArgs } from 'node:util';
import { unzipSync, type Zippable, type ZipOptions, zipSync } from 'fflate';
import { strcmp } from './lib/php';
import { readSources } from './lib/sources';

const ROOT = resolve(import.meta.dir, '..');
/** Icon themes generated by scripts/build-data.ts (resources/data/<theme>.php + resources/icons/<theme>/). */
const THEMES = ['material', 'datapack'] as const;
/** Pelican's import limit (config panel.plugin.max_import_size, default 100 MiB). */
const MAX_SIZE = 100 * 1024 * 1024;

const { values: args } = parseArgs({
    options: {
        out: { type: 'string', default: join(ROOT, 'dist') },
        'skip-data-check': { type: 'boolean', default: false },
        'download-url': { type: 'string' },
        help: { type: 'boolean', short: 'h', default: false },
    },
    strict: true,
});
if (args.help) {
    console.log('usage: bun scripts/release.ts [--out <dir>] [--skip-data-check] [--download-url <url>]');
    process.exit(0);
}

const warnings: string[] = [];
const warn = (message: string) => {
    warnings.push(message);
    console.warn(`[release] warning: ${message}`);
};
function fail(message: string): never {
    console.error(`[release] error: ${message}`);
    process.exit(1);
}

// --- plugin.json ---------------------------------------------------------------------------------
const pluginPath = join(ROOT, 'plugin.json');
if (!existsSync(pluginPath)) {
    fail('plugin.json is missing');
}
const pluginRaw = readFileSync(pluginPath, 'utf8');
let plugin: Record<string, unknown> = {};
try {
    plugin = JSON.parse(pluginRaw) as Record<string, unknown>;
} catch (err) {
    fail(`plugin.json is not valid JSON: ${(err as Error).message}`);
}
if (typeof plugin !== 'object' || plugin === null || Array.isArray(plugin)) {
    fail('plugin.json must contain a JSON object');
}
const id = plugin.id;
const version = plugin.version;
if (typeof id !== 'string' || !/^[a-z0-9][a-z0-9-]*$/.test(id)) {
    fail(`plugin.json: invalid id ${JSON.stringify(id)}`);
}
if (typeof version !== 'string' || !/^[0-9A-Za-z][0-9A-Za-z.+-]*$/.test(version)) {
    fail(`plugin.json: invalid version ${JSON.stringify(version)}`);
}
if (id !== 'file-icons') {
    warn(`plugin id is ${JSON.stringify(id)}, expected "file-icons" (the plugin folder must equal the id)`);
}
let pluginJson = pluginRaw;
if (Object.hasOwn(plugin, 'meta')) {
    delete plugin.meta;
    pluginJson = `${JSON.stringify(plugin, null, 4)}\n`;
    warn('stripped the "meta" key from plugin.json (Pelican would otherwise import its status as-is)');
}

// --- generated data must be current ----------------------------------------------------------------
if (!args['skip-data-check']) {
    const r = spawnSync(process.execPath, [join(ROOT, 'scripts', 'build-data.ts'), '--check'], { cwd: ROOT, stdio: 'inherit' });
    if (r.status !== 0) {
        fail('generated data is out of date - run `bun run build` first (or pass --skip-data-check)');
    }
}

// --- collect files -------------------------------------------------------------------------------
const files = new Map<string, Uint8Array>(); // path relative to the plugin root => bytes
const skipped: string[] = [];

function addFile(rel: string): void {
    const abs = join(ROOT, rel);
    const st = lstatSync(abs);
    if (st.isSymbolicLink()) {
        warn(`skipping symlink ${rel}`);
        return;
    }
    if (!st.isFile()) {
        warn(`skipping ${rel} (not a regular file)`);
        return;
    }
    files.set(rel, readFileSync(abs));
}

function addDir(rel: string): number {
    const before = files.size;
    const walk = (dir: string) => {
        for (const entry of readdirSync(join(ROOT, dir), { withFileTypes: true }).sort((a, b) => strcmp(a.name, b.name))) {
            const child = `${dir}/${entry.name}`;
            if (entry.name.startsWith('.')) {
                skipped.push(child);
                continue;
            }
            if (entry.isSymbolicLink()) {
                warn(`skipping symlink ${child}`);
            } else if (entry.isDirectory()) {
                walk(child);
            } else if (entry.isFile()) {
                addFile(child);
            } else {
                warn(`skipping ${child} (not a regular file)`);
            }
        }
    };
    walk(rel);
    return files.size - before;
}

const required = (rel: string, kind: 'file' | 'dir') => {
    const abs = join(ROOT, rel);
    const ok = existsSync(abs) && (kind === 'file' ? lstatSync(abs).isFile() : lstatSync(abs).isDirectory());
    if (!ok) {
        fail(`${rel} is missing`);
    }
};
const optional = (rel: string, kind: 'file' | 'dir'): boolean => {
    const abs = join(ROOT, rel);
    if (!existsSync(abs) || (kind === 'file' ? !lstatSync(abs).isFile() : !lstatSync(abs).isDirectory())) {
        warn(`${rel}${kind === 'dir' ? '/' : ''} is missing - not included`);
        return false;
    }
    return true;
};

required('src', 'dir');
required('resources/data/languages.php', 'file');
for (const theme of THEMES) {
    required(`resources/data/${theme}.php`, 'file');
    required(`resources/icons/${theme}`, 'dir');
}
if (existsSync(join(ROOT, 'resources', 'data', 'manifest.php'))) {
    fail('resources/data/manifest.php is a leftover of the old data layout - run `bun run build`');
}
files.set('plugin.json', Buffer.from(pluginJson, 'utf8'));
for (const f of ['README.md', 'LICENSE', 'THIRD_PARTY_NOTICES.md', 'CHANGELOG.md']) {
    if (optional(f, 'file')) {
        addFile(f);
    }
}
const alwaysPresent = new Set(['resources/data', 'resources/icons', 'src']);
for (const d of ['config', 'database', 'lang', 'resources/data', 'resources/icons', 'resources/views', 'src']) {
    if ((alwaysPresent.has(d) || optional(d, 'dir')) && addDir(d) === 0) {
        warn(`${d}/ is empty`);
    }
}
for (const theme of THEMES) {
    if (![...files.keys()].some((f) => f.startsWith(`resources/icons/${theme}/`) && f.endsWith('.svg'))) {
        fail(`resources/icons/${theme}/ contains no icons - run \`bun run build\``);
    }
}
if (existsSync(join(ROOT, 'database')) && ![...files.keys()].some((f) => f.startsWith('database/migrations/') && f.endsWith('.php'))) {
    warn('database/migrations/ contains no migration - the per-user preference table would not be created');
}
// the bundled icon themes are MIT licensed: their notices must ship with the plugin
const notices = files.get('THIRD_PARTY_NOTICES.md');
if (notices) {
    const text = new TextDecoder().decode(notices);
    const copyrights = ['Copyright (c) 2025 Material Extensions', ...Object.values(readSources(join(ROOT, 'scripts', 'data', 'sources.json'))).map((s) => s.copyright)];
    for (const copyright of copyrights) {
        if (!text.includes(copyright)) {
            warn(`THIRD_PARTY_NOTICES.md does not contain "${copyright}"`);
        }
    }
}
if (existsSync(join(ROOT, 'resources'))) {
    for (const entry of readdirSync(join(ROOT, 'resources'))) {
        if (!['data', 'icons', 'views'].includes(entry)) {
            warn(`resources/${entry} is not part of the release (only data, icons, views are shipped)`);
        }
    }
}

// --- validate entry names (Pelican rejects any name containing '..' or starting with '/') -------
for (const rel of files.keys()) {
    if (rel.includes('..') || rel.startsWith('/') || rel.includes('\\') || /[\0-\x1f:*?"<>|]/.test(rel)) {
        fail(`refusing to package ${JSON.stringify(rel)} (path traversal or unportable name)`);
    }
    if (/\.(php|json|md|svg)$/.test(rel) || rel === 'LICENSE') {
        const bytes = files.get(rel)!;
        if (Buffer.from(bytes.buffer, bytes.byteOffset, bytes.byteLength).includes('\r\n')) {
            warn(`${rel} has CRLF line endings`);
        }
    }
}

// --- build the archive ---------------------------------------------------------------------------
function fixedTime(): Date {
    const epoch = process.env.SOURCE_DATE_EPOCH;
    if (epoch !== undefined && epoch !== '') {
        if (!/^\d+$/.test(epoch)) {
            fail(`SOURCE_DATE_EPOCH must be an integer, got ${JSON.stringify(epoch)}`);
        }
        const utc = new Date(Number(epoch) * 1000);
        if (utc.getUTCFullYear() < 1980 || utc.getUTCFullYear() > 2107) {
            fail('SOURCE_DATE_EPOCH is outside the ZIP date range (1980-2107)');
        }
        // ZIP stores local "wall clock" fields; fflate reads them with local getters
        return new Date(utc.getUTCFullYear(), utc.getUTCMonth(), utc.getUTCDate(), utc.getUTCHours(), utc.getUTCMinutes(), utc.getUTCSeconds());
    }
    return new Date(1980, 1, 1, 0, 0, 0); // like Gradle: a month after the DOS epoch, so no time zone shift underflows it
}
const mtime = fixedTime();
const fileOpts: ZipOptions = { level: 9, mtime, os: 3, attrs: (0o100644 << 16) >>> 0 };
const dirOpts: ZipOptions = { level: 0, mtime, os: 3, attrs: ((0o040755 << 16) | 0x10) >>> 0 };

const paths = [...files.keys()].sort(strcmp);
const dirs = new Set<string>([`${id}/`]);
for (const rel of paths) {
    const parts = rel.split('/');
    for (let i = 1; i < parts.length; i++) {
        dirs.add(`${id}/${parts.slice(0, i).join('/')}/`);
    }
}
const entries: [string, Uint8Array, ZipOptions][] = [
    ...[...dirs].map((d) => [d, new Uint8Array(0), dirOpts] as [string, Uint8Array, ZipOptions]),
    ...paths.map((rel) => [`${id}/${rel}`, files.get(rel)!, fileOpts] as [string, Uint8Array, ZipOptions]),
].sort(([a], [b]) => strcmp(a, b));
const zippable: Zippable = {};
for (const [name, data, opts] of entries) {
    zippable[name] = [data, opts];
}
const zip = zipSync(zippable);

const uncompressed = paths.reduce((n, rel) => n + files.get(rel)!.length, 0);
if (zip.length > MAX_SIZE || uncompressed > MAX_SIZE) {
    fail(`archive too large for Pelican's default import limit (${zip.length} compressed / ${uncompressed} uncompressed bytes)`);
}

// self-check: round-trip and the layout Pelican's importer expects
const back = unzipSync(zip);
const names = Object.keys(back);
if (names.length !== entries.length || !back[`${id}/plugin.json`]) {
    fail('round-trip check of the archive failed');
}
for (const rel of paths) {
    const a = back[`${id}/${rel}`];
    const b = files.get(rel)!;
    if (!a || Buffer.compare(Buffer.from(a), Buffer.from(b)) !== 0) {
        fail(`round-trip mismatch for ${rel}`);
    }
}
if (Object.hasOwn(JSON.parse(new TextDecoder().decode(back[`${id}/plugin.json`])) as object, 'meta')) {
    fail('plugin.json in the archive still has a meta key');
}

mkdirSync(args.out!, { recursive: true });
const target = join(resolve(args.out!), `${id}-${version}.zip`);
const tmp = `${target}.${process.pid}.tmp`;
writeFileSync(tmp, zip);
renameSync(tmp, target);

const sha256 = createHash('sha256').update(zip).digest('hex');
const counts = new Map<string, number>();
for (const rel of paths) {
    const depth = rel.startsWith('resources/icons/') ? 3 : rel.startsWith('resources/') ? 2 : 1;
    const top = rel.includes('/') ? rel.split('/').slice(0, depth).join('/') + '/' : rel;
    counts.set(top, (counts.get(top) ?? 0) + 1);
}
console.log(`[release] ${relative(ROOT, target).split('\\').join('/') || target}`);
console.log(`[release] ${paths.length} files (${[...counts].map(([k, n]) => `${k} ${n}`).join(', ')})`);
console.log(`[release] size ${zip.length} bytes (${uncompressed} uncompressed), mtime ${mtime.toString()}`);
if (skipped.length) {
    console.log(`[release] skipped dotfiles: ${skipped.join(', ')}`);
}
console.log(`[release] sha256 ${sha256}`);
const downloadUrl = args['download-url']?.split('{version}').join(version);
if (downloadUrl !== undefined && !/^https:\/\/\S+\.zip$/.test(downloadUrl)) {
    fail(`--download-url must be an https URL ending in .zip, got ${downloadUrl}`);
}
const updateJson = `${JSON.stringify({ '*': { version, download_url: downloadUrl ?? '<fill in>', sha256 } }, null, 4)}\n`;
if (downloadUrl !== undefined) {
    const updateTarget = join(resolve(args.out!), 'update.json');
    writeFileSync(updateTarget, updateJson);
    console.log(`[release] ${relative(ROOT, updateTarget).split('\\').join('/') || updateTarget}:`);
} else {
    console.log('[release] update.json (pass --download-url to write it):');
}
process.stdout.write(updateJson);
if (warnings.length) {
    console.log(`[release] ${warnings.length} warning(s), see above`);
}
